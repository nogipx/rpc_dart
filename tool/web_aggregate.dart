import 'dart:io';

/// Writes a package's web-runnable tests into a few aggregate entry points, so
/// `dart test -p node` compiles each aggregate once instead of every test file
/// on its own: dart2js recompiles the whole library for every suite.
///
/// Usage (from the repo root):
///   fvm dart run tool/web_aggregate.dart <package dir> [shards]
///
///   fvm dart run tool/web_aggregate.dart packages/core/rpc_dart 4
///   (cd packages/core/rpc_dart && fvm dart test -p node -j 4 .dart_tool/web_aggregate)
///
/// Output goes to `<package>/.dart_tool/web_aggregate/all_<i>_test.dart`,
/// rewritten on every run and never committed, so it cannot fall behind the
/// tests. Each test file becomes one `group` named by its path under `test/`.
///
/// A file annotated `@TestOn('vm')` is left out: it may import `dart:io`,
/// which dart2js cannot compile. Any other `@TestOn` selector is carried to
/// the group's `testOn:`. Any other library-level annotation stops the run:
/// importing a file drops its library annotations, so one would be lost.
void main(List<String> args) {
  if (args.isEmpty || args.length > 2) {
    stderr.writeln('Usage: web_aggregate.dart <package dir> [shards]');
    exit(64);
  }
  final package = Directory(args[0]);
  final shards = args.length > 1 ? int.tryParse(args[1]) : 4;
  if (shards == null || shards < 1) {
    stderr.writeln('shards must be a positive integer, got "${args[1]}"');
    exit(64);
  }
  final testDir = Directory('${package.path}/test');
  if (!testDir.existsSync()) {
    stderr.writeln('No test/ directory in ${package.path}');
    exit(1);
  }

  final suites = <_Suite>[];
  var skipped = 0;
  final files =
      testDir
          .listSync(recursive: true)
          .whereType<File>()
          .where((f) => f.path.endsWith('_test.dart'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in files) {
    final relative = file.path.substring(testDir.path.length + 1);
    final testOn = _testOn(file, relative);
    if (testOn == 'vm') {
      skipped++;
      continue;
    }
    suites.add(_Suite(relative, testOn, file.lengthSync()));
  }

  // Greedy by size, largest first, so the aggregates compile and run in
  // similar time.
  final bins = List.generate(shards, (_) => <_Suite>[]);
  final weights = List.filled(shards, 0);
  for (final suite in [...suites]..sort((a, b) => b.bytes - a.bytes)) {
    var lightest = 0;
    for (var i = 1; i < shards; i++) {
      if (weights[i] < weights[lightest]) lightest = i;
    }
    bins[lightest].add(suite);
    weights[lightest] += suite.bytes;
  }

  final out = Directory('${package.path}/.dart_tool/web_aggregate');
  if (out.existsSync()) out.deleteSync(recursive: true);
  out.createSync(recursive: true);
  for (var i = 0; i < shards; i++) {
    final bin = bins[i]..sort((a, b) => a.path.compareTo(b.path));
    if (bin.isEmpty) continue;
    File('${out.path}/all_${i}_test.dart').writeAsStringSync(_aggregate(bin));
  }
  stdout.writeln(
    '${suites.length} suites in ${bins.where((b) => b.isNotEmpty).length} '
    'aggregates under ${out.path} ($skipped VM-only left out)',
  );
}

final class _Suite {
  _Suite(this.path, this.testOn, this.bytes);
  final String path;
  final String? testOn;
  final int bytes;
}

final _annotation = RegExp(r'^@(\w+)');
final _testOnArg = RegExp(r'''^@TestOn\(\s*(['"])(.*)\1\s*\)''');

/// The file's `@TestOn` selector, or null. Exits on any other library-level
/// annotation.
String? _testOn(File file, String relative) {
  String? selector;
  for (final line in file.readAsLinesSync()) {
    final trimmed = line.trim();
    if (trimmed.startsWith('library') ||
        trimmed.startsWith('import ') ||
        trimmed.startsWith('export ') ||
        trimmed.startsWith('part ') ||
        trimmed.startsWith('void main')) {
      break;
    }
    final name = _annotation.firstMatch(trimmed)?.group(1);
    if (name == null) continue;
    final arg = _testOnArg.firstMatch(trimmed);
    if (name == 'TestOn' && arg != null) {
      selector = arg.group(2);
      continue;
    }
    stderr.writeln(
      'test/$relative: library annotation "$trimmed" would be lost in an '
      'aggregate; carry it in tool/web_aggregate.dart first',
    );
    exit(1);
  }
  return selector;
}

String _aggregate(List<_Suite> suites) {
  final b = StringBuffer()
    ..writeln('// Generated by tool/web_aggregate.dart. Do not edit.')
    ..writeln('@TestOn(\'js\')')
    ..writeln('library;')
    ..writeln()
    ..writeln("import 'package:test/test.dart';")
    ..writeln();
  for (var i = 0; i < suites.length; i++) {
    b.writeln("import '../../test/${suites[i].path}' as t$i;");
  }
  b
    ..writeln()
    ..writeln('void main() {');
  for (var i = 0; i < suites.length; i++) {
    final testOn = suites[i].testOn;
    final extra = testOn == null ? '' : ", testOn: '$testOn'";
    b.writeln("  group('${suites[i].path}', t$i.main$extra);");
  }
  b.writeln('}');
  return b.toString();
}
